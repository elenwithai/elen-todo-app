function getDailyQuote(date) {
  var d = date || new Date();
  var start = new Date(d.getFullYear(), 0, 0);
  var diff = d - start;
  var oneDay = 1000 * 60 * 60 * 24;
  var dayOfYear = Math.floor(diff / oneDay); // 1-based
  var idx = (dayOfYear - 1) % DAILY_QUOTES.length;
  if (idx < 0) idx += DAILY_QUOTES.length;
  return DAILY_QUOTES[idx];
}
